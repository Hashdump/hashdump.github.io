<h1>Proposed Constitution</h1>

<p>This draft document shows proposed changes to the Hashdump Constitution as of <b>November 11th, 2026</b>. A summary of the changes is as follows:</p>

<ul>
    <li>Replace references to <q>Security Club</q> with the more commonly-used name <q>Hashdump</q> or <q>Hashdump Security Club</q></li>
    <li>Replace the abbreviation CSU with the full name Colorado State University where applicable</li>
    <li>Make pronoun usage consistent across the document</li>
    <li>Clarify that alumni members were previously active members of the organization</li>
    <li>Reorder officer positions for consistency</li>
    <li>Clarify that the terms Treasurer and Financial Officer refer to the same position</li>
    <li>Allow officers to serve partial terms lasting less than a school year, and introduce a resignation mechanism, with a resigning President or Treasurer needing to provide two weeks advance notice if possible</li>
    <li>Allow ad-hoc officer elections midway through the school year to fill vacant seats, with one week advance notice to club members</li>
    <li>Adjust language about advisor requirements (be staff, faculty, or an approved graduate student) to be closer to language in the current model constitution</li>
    <li>Remove the requirement that the advisor attend two regular business meetings per month, thereby making their attendance optional</li>
    <li>Update references to CSU offices (Division of IT; Systems and Network Administration; and Student Leadership, Involvement &amp; Community Engagement)</li>
    <li>Correct inconsistencies in Bylaws and Unapproved Actions section headings</li>
    <li>Make overall tweaks to grammar and formatting</li>
</ul>

<p>For the remainder of this document, removed text is <del>struck through in pink</del>, while additions are <ins>underlined in yellow</ins>.</p>

<h2>ARTICLE I - NAME</h2>

<p>This organization shall be called <q><ins>Hashdump</ins> Security Club</q> with an alias of <q>Hash<del>D</del><ins>d</ins>ump.</q> Any reference to this club can be stated as <q><ins>Hashdump</ins> Security Club at Colorado State University.</q></p>

<h2>ARTICLE II - PURPOSE</h2>

<p>The purpose of this club is to increase members<ins>'</ins> understanding of how to keep a given system secure. This system can be any combination of physical, social<ins>,</ins> or electronic medias.</p>

<h2>ARTICLE III - MEMBERSHIP</h2>

<h3>Section 1: Active Members</h3>

<p>Active membership is open to all students at Colorado State University <del>(CSU)</del> with the right to vote and hold office.</p>

<h3>Section 2: Associate Members</h3>

<p>Associate membership is open to faculty and interested people outside the University setting, for example, <ins>the</ins> Fort Collins community; they may not vote or hold office.</p>

<h3>Section 3: Alumni Members</h3>

<p>Alumni membership is open to former <del>CSU</del><ins>Colorado State University</ins> students who were <ins>active</ins> members of the organization; they may not vote or hold office.</p>

<h3>Section 4: Membership Rules of Order</h3>

<p>We expect members to be dedicated to the mission of supporting <del>the</del><ins>Hashdump</ins> Security Club, to be friendly and open-minded, to work hard and to ascribe to the highest professional standards of conduct. As a recognized student organization at Colorado State University, our organization shall not deny membership to any student on the basis of race, age, creed, color, religion, national origin or ancestry, sex, gender, disability, veteran status, genetic information, sexual orientation, gender identity or expression, or pregnancy.</p>

<h3>Section 5: Duties of Members</h3>

<p>It is a member’s responsibility to participate in club events and provide constructive feedback. A member shall be responsible for using the information shared in this club in a legal, ethical manner and will be required to uphold the ethical code described in the bylaws <del>or</del><ins>and</ins> manual. Club times will be determined at the start of every semester based on the time when the largest number of people can attend.</p>

<h3>Section 6: Dues</h3>

<p>The annual due amount will be decided at the start of each academic year by the current officers. The payment of these dues will qualify a member for a membership of one academic year. A member is able to vote for officers if and only if they have paid their dues.</p>

<h3>Section 7: Removal of Members</h3>

<p>Members can be removed from this club upon the performance of any act which is illegal, unethical, unprofessional<ins>,</ins> or breaks any of the rules stated in this constitution or in any of the bylaws. The removal of a member against <del>his/her</del><ins>their</ins> will needs to have the approval of two<del> </del><ins>-</ins>thirds of the officers. Should a member decide that <del>he/she wishes</del><ins>they wish</ins> to remove themselves from the club, they will simply need to contact an officer. All removal procedures should follow due process, including adequate written notice (seven days minimum), the right to speak on one’s behalf, and <ins>the</ins> right to an appeal.</p>

