<h3>Section 3: Election of Officers</h3>

<h4><ins>Subsection A: Election Restrictions &amp; Voting Protocol</ins></h4>

<p>Candidates can be nominated or self-nominated. The requirements for an officer to hold a position include (a) a minimum 2.25 GPA and (b) a willingness and ability to hold the office for the academic year. Elections will be held by a simple vote of showing hands. A simple majority is required for election to office.</p>

<h4><ins>Subsection B: Term Duration &amp; Limits</ins></h4>

<p>The term of each officer shall be one academic year with no term limits. <ins>It is acceptable that the elected officer only be able to serve for one semester or less, either by Fall graduation, academic transfer, or extenuating circumstance which leads said officer to abandon their post. An elected officer may resign at their discretion by notifying the other officers. However, if this officer occupies a necessary position (President or Treasurer), then any resignation must be announced at least two weeks in advance when possible.</ins></p>

<h4><ins>Subsection C: Date of Elections</ins></h4>

<p>Officers will be elected for each academic year at the end of the previous academic year<ins>,</ins> with the exception of the first year where elections shall be held at the beginning of that year. <del>For example the elections for the academic year of 2012 will be held at the end of the 2011 academic year.</del> The second<ins>-</ins>to<ins>-</ins>last business meeting of every year will include election of new officers. <ins>However, ad-hoc officer elections for posts that have been abandoned (see Subsection B) or are open can also be held, with one week's prior notice, during a general business meeting.</ins></p>

<h3>Section 4: Removal of Officers</h3>

<p>Officers will be removed from their <del>office of</del><ins>position in</ins> <del>the</del><ins>Hashdump</ins> Security Club for not fulfilling duties assigned to them or for acting in an unethical or unprofessional manner. We believe <del>on</del><ins>in</ins> a constructive process, so the officer will first have the opportunity to discuss these issues with the other officers. Should this not resolve the issue, the members of the organization will vote, following due process, and if majority vote is received the officer will be give<ins>n</ins> seven days minimum <ins>with a</ins> written notice that they will be removed. The officer will be informed that, as per due process, they have the right to speak on their behalf, and the right to an appeal. The appeal must be in writing, and must be accompanied by a formal me<ins>e</ins>ting with the other elected officers to determine the status of the appeal. Any issues of conduct problems or academic integrity issues will also involve the Office of Conflict and Resolution and Student <del>c</del><ins>C</ins>onduct Services at Colorado State University.</p>

<h2>ARTICLE V - MEETINGS</h2>

<h3>Section 1: Business Meetings</h3>

<p>Business meetings shall be held at least twice a month on a given day decided at the beginning of each semester.</p>

<h3>Section 2: Executive Board Meetings</h3>

<p>Executive board meetings shall be held at least once a month.</p>

<h2>ARTICLE VI - ADVISOR</h2>

<h3>Section 1: Election</h3>

<p>The Academic Advisor will be decided by a vote from the club officers. The Academic Advisor will be selected from a group of potential advisors who have either been nominated by the officers, or who have nominated themselves. The Academic Advisor who has a two thirds vote will be appointed as the Academic Advisor.</p>

<h3>Section 2: Qualifications</h3>

<p>The advisor must be a <del>CSU faculty/staff member</del><ins>recognized Colorado State University employee as a faculty or staff member,</ins> or graduate student (with <del>a</del> consent <del>form</del> from their academic advisor) who has an interest in serving as an advisor.</p>

<h3>Section 3: Duties</h3>

<p>The advisor <del>will be present for at least two business meetings per month</del><ins>may, optionally, be present for business or executive board meetings</ins>. The advisor serves as a support and guidance to the Security Club. The advisor may not vote but can offer advice to the organization.</p>

<h2>ARTICLE VII - AMENDMENTS</h2>

<p>This constitution may be amended at any regular business meeting of the organization by two-thirds vote of active membership, provided that the amendment has been submitted in writing at least one week prior to the business meeting and has been published to the general membership for review.<del>.</del></p>

<h2>ARTICLE VIII - FINANCIAL STRUCTURE</h2>

<p>The job of coordinating the financial budget for each academic year is determined by the Treasurer with guidance from the Academic Advisor. Should there be membership dues, these dues will be deposited directly into an account which is managed through <del>CSU student organizations office</del><ins>the Student Leadership, Involvement &amp; Community Engagement (SLiCE) office</ins>.</p>

<h2>ARTICLE <del>VI</del><ins>IX</ins> - BYLAWS</h2>

<h3>Section 1: Dues</h3>

<p>The annual due for the academic year of 20<del>12</del><ins>26</ins> shall be zero dollars and zero cents<ins>.</ins></p>

<h3>Section 2: Who this applies to</h3>

<p>This constitution applies to anyone who has participated in any <del>of the</del><ins>Hashdump</ins> Security Club meetings. Therefore if a participant attends one meeting, and uses any information discussed in an illegal manner, they will be bound to this constitution.</p>

<h3>Section 3: Demos</h3>

<p>Should a topic discussed require a demo of a given technology, that demo must adhere to the <del>ACNS</del><ins><a href="https://it.csusystem.edu/">DoIT</a> and <a href="https://sna.cs.colostate.edu/">SNA</a></ins> policies stated on their website<ins>s</ins> and must not interfere with the operation of any <del>CSU</del><ins>Colorado State University</ins> services. Should the given demo require access to multiple machines, prior authorization must be given by the appropriate representative.</p>

<h3>Section 4: Ethical Code</h3>

<p>Many of the topics that will be covered during the meetings can be used for malicious intent. Thus<ins>,</ins> any and all information discussed during the meetings is to be used for EDUCATIONAL PURPOSES ONLY. Should it be discovered that any member is using this information for illegal activities, that member shall be removed from the club following the guidelines stated in Article III<ins>,</ins> Section 7. It is not ethical to use information obtained through this club to access any information not meant for the public eye without prior approval, nor is it ethical to gain access to any system in which you are not authorized.</p>

<h3>Section 5: <ins>Unapproved Actions</ins></h3>

<p>Any action performed by a member of this club without prior approval of the officers will be acting upon their own accord and those actions will not be affiliated with this club. In the event that a member performs an action that has not been approved by the club then that member was NOT acting on behalf of <del>the</del><ins>Hashdump</ins> Security Club <del>at CSU</del> and that member shall hold sole responsibility for their actions. The member who performs any illegal activity shall be dismissed from the club as described in Article III<ins>,</ins> Section 7.</p>

